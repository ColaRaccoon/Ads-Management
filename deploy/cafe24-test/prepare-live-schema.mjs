import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { spawnSync } from "node:child_process";

// A deterministic DDL input, not a second Prisma client or an application migration.
// Keeping every selected model's scalar fields permits the application's existing
// writer/import services to use their ordinary generated Prisma metadata.
const root = path.resolve(fileURLToPath(new URL("../..", import.meta.url)));
const selected = new Set([
  "AppUser", "SecurityAuditEvent", "Product", "ProductCostRule", "ExchangeRate",
  "Cafe24UploadBatch", "Cafe24OrderLine", "Cafe24CouponRule", "Cafe24ProductRule",
  "Cafe24UploadRowError", "SourceConnection", "Cafe24OauthAttempt", "SourcePolicy",
  "SyncRun", "RunUnit", "SyncLease", "SourceCoverage", "SourceRecordLink",
  "Cafe24OrderApiVersion", "SourceCredential", "Cafe24ObservedOrderRevision",
  "Cafe24ObservedDayCheckpoint"
]);
const original = readFileSync(path.join(root, "apps/api/prisma/schema.prisma"), "utf8");
const blocks = [...original.matchAll(/^(model|enum|generator|datasource) (\w+) \{\r?\n[\s\S]*?^\}/gm)];
const modelNames = new Set(blocks.filter((match) => match[1] === "model").map((match) => match[2]));
const enums = new Map(blocks.filter((match) => match[1] === "enum").map((match) => [match[2], match[0]]));
const models = blocks.filter((match) => match[1] === "model" && selected.has(match[2])).map((match) => {
  const removedFields = new Set();
  const lines = match[0].split(/\r?\n/).filter((line) => {
    const field = /^\s+(\w+)\s+(\w+)(?:\[\]|\?)?(?:\s|$)/.exec(line);
    if (!field || !modelNames.has(field[2]) || selected.has(field[2])) return true;
    removedFields.add(field[1]);
    return false;
  });
  if (lines.some((line) => line.trim().startsWith("@@") &&
      [...removedFields].some((field) => new RegExp(`\\b${field}\\b`).test(line))))
    throw new Error("LIVE_SCHEMA_RELATION_INDEX_REQUIRES_REVIEW");
  return lines.join("\n");
});
if (models.length !== selected.size) throw new Error("LIVE_SCHEMA_MODEL_INVENTORY_MISMATCH");
const body = models.join("\n\n");
const usedEnums = [...enums].filter(([name]) => new RegExp(`\\b${name}\\b`).test(body)).map(([, block]) => block);
const header = '// Generated by deploy/cafe24-test/prepare-live-schema.mjs. Review before use.\n' +
  '// Only additional 06 tables may be applied to the already verified test DB.\n' +
  'datasource db {\n  provider = "postgresql"\n  url = env("DATABASE_URL")\n}\n';
const output = `${header}\n${usedEnums.join("\n\n")}\n\n${body}\n`;
writeFileSync(path.join(root, "apps/api/prisma/cafe24-live.schema.prisma"), output);
if (process.argv.includes("--sql")) {
  const diff = spawnSync(process.execPath, [path.join(root, "node_modules/prisma/build/index.js"),
    "migrate", "diff", "--from-empty", "--to-schema-datamodel",
    path.join(root, "apps/api/prisma/cafe24-live.schema.prisma"), "--script"], {
    cwd: root, encoding: "utf8", maxBuffer: 2 * 1024 * 1024,
    env: { ...process.env, DATABASE_URL: "postgresql://schema:shape@127.0.0.1:1/shape" }
  });
  if (diff.status !== 0) throw new Error("LIVE_SCHEMA_SQL_GENERATION_FAILED");
  const existingTables = new Set(["source_connections", "source_credentials", "security_audit_events",
    "cafe24_oauth_attempts", "cafe24_observed_order_revisions", "cafe24_observed_day_checkpoints"]);
  const existingTypes = new Set(["SourceProvider", "SourceAccessState",
    "security_audit_actor_type", "security_audit_result"]);
  const statements = diff.stdout.replace(/^--[^\n]*\n/gm, "").split(";").map((item) => item.trim()).filter(Boolean);
  const additive = statements.filter((statement) => {
    const type = /^CREATE TYPE "([^"]+)" AS ENUM\b/.exec(statement);
    if (type) return !existingTypes.has(type[1]);
    const table = /^CREATE TABLE "([^"]+)"/.exec(statement) ||
      /^CREATE (?:UNIQUE )?INDEX "[^"]+" ON "([^"]+)"/.exec(statement) ||
      /^ALTER TABLE "([^"]+)" ADD CONSTRAINT\b/.exec(statement);
    if (!table) throw new Error("LIVE_SCHEMA_SQL_STATEMENT_REQUIRES_REVIEW");
    return !existingTables.has(table[1]);
  });
  const newTables = additive.flatMap((statement) => /^CREATE TABLE "([^"]+)"/.exec(statement)?.[1] ?? []);
  if (newTables.length !== 16 || newTables.some((name) => /meta|google|coupang/.test(name)))
    throw new Error("LIVE_SCHEMA_TABLE_INVENTORY_MISMATCH");
  const guards = readFileSync(path.join(root, "deploy/cafe24-test/live-additive-guards.sql"), "utf8");
  const invariants = readFileSync(path.join(root, "deploy/cafe24-test/live-additive-invariants.sql"), "utf8");
  const sql = `${guards}\n${additive.map((statement) => `${statement};`).join("\n\n")}\n\n` +
    `${invariants}\n${newTables.map((name) => `ALTER TABLE "${name}" ENABLE ROW LEVEL SECURITY;`).join("\n")}\nCOMMIT;\n`;
  writeFileSync(path.join(root, "deploy/cafe24-test/live-additive.sql"), sql);
}
process.stdout.write(`LIVE_SCHEMA_PREPARED models=${models.length} enums=${usedEnums.length}\n`);
